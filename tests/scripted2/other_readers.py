#!/usr/bin/env python3
"""Score the Codex and Gemini readers on the second test's twelve runs,
against its settled key (DECISIONS.md, Oct 16). Not preregistered, and
reported that way: the preregistered test covered Claude's two paths.

    python3 tests/scripted2/other_readers.py read codex-cli    # on the author's Codex account
    python3 tests/scripted2/other_readers.py read gemini-cli   # on the author's Gemini account
    python3 tests/scripted2/other_readers.py score codex-cli   # (or gemini-cli) against the key

read: as score.py's read, through the plugin's reader with --backend, into
reader-runs/<backend>/<task>-<cell>/. It refuses to start unless the reader,
the checklists, the key, and score.py are committed unchanged.

score: score.py's scoring, unchanged, for this backend alone, into
reader-runs/score-<backend>.md and .json. The same bar as the preregistered
test (κ of at least 0.6 on the three primary codes); a reader that falls
short is still offered, with a note in its disclosures (DECISIONS.md, Oct 16).
"""
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import score  # noqa: E402

BACKENDS = ("codex-cli", "gemini-cli")


def read(backend):
    changed = score.sh(["git", "status", "--porcelain", "--", *score.FROZEN], score.REPO).strip()
    if changed:
        sys.exit(f"Commit these first, so the reader and the key are fixed:\n{changed}")
    for (task, cell), bundle in score.runs().items():
        out = score.OUT / backend / f"{task}-{cell}"
        if (out / "codes.json").exists():
            print(f"{backend} {task} {cell}: already read", flush=True)
            continue
        base = Path(score.tempfile.mkdtemp(prefix=f"wd-other-{task}-{cell}-"))
        score.sh(["git", "clone", "-q", str(bundle), str(base / "project")])
        score.sh(["git", "-C", str(base / "project"), "fetch", "-q", str(bundle), "refs/provenance/*:refs/provenance/*"])
        print(f"{backend} {task} {cell}: reading …", flush=True)
        r = subprocess.run([sys.executable, str(score.READER), str(base / "project"), "--work", *score.TASKS[task]["work"],
                            "--packs", *score.PACKS[task], "--backend", backend, "--out", str(out)],
                           capture_output=True, text=True)
        print(r.stdout.strip() or r.stderr.strip()[-400:], flush=True)
        score.shutil.rmtree(base)
        if r.returncode:
            sys.exit(f"{backend} {task} {cell}: the reader failed; rerun to continue from here")
    head = score.sh(["git", "rev-parse", "HEAD"], score.REPO).strip()
    (score.OUT / backend / "read.json").write_text(json.dumps(
        {"repo_head": head, "backend": backend, "preregistered": False,
         "runs": {f"{t}-{c}": b.name for (t, c), b in score.runs().items()}}, indent=1) + "\n")


def score_backend(backend):
    result = score.score_path(backend, score.runs())
    lines = [f"# The {backend} reader scored against the settled key", "",
             "*Generated by `tests/scripted2/other_readers.py`. Not preregistered: the preregistered test covered "
             "Claude's two paths (DECISIONS.md, Oct 16).*", "",
             f"**Clears the bar (κ ≥ 0.6 on all three primary codes): {'yes' if result['validated'] else 'no'}.**", "",
             "| Layer | n | agreement | κ |", "| :- | -: | -: | -: |"]
    for name, r in result["layers"].items():
        tag = " (primary)" if name in score.PRIMARY else " (second layer)"
        lines.append(f"| {name}{tag} | {r['n']} | {score._pct(r['agreement'])} | {score._num(r['kappa'])} |")
    lines += ["", "| Run | Key units | Found | Reader units |", "| :- | -: | -: | -: |"]
    lines += [f"| {r} | {v['key units']} | {v['found']} | {v['reader units']} |" for r, v in result["listing"].items()]
    (score.OUT / f"score-{backend}.md").write_text("\n".join(lines) + "\n")
    (score.OUT / f"score-{backend}.json").write_text(json.dumps({k: v for k, v in result.items() if k != "mismatches"},
                                                                indent=1) + "\n")
    print("\n".join(lines[:8 + len(result["layers"])]))


if __name__ == "__main__":
    args = sys.argv[1:]
    if len(args) == 2 and args[0] in ("read", "score") and args[1] in BACKENDS:
        (read if args[0] == "read" else score_backend)(args[1])
    else:
        sys.exit(__doc__)
    for p in score._clones.values():
        score.shutil.rmtree(p.parent, ignore_errors=True)
